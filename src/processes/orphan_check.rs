use std::{
    collections::HashSet,
    path::{Path, PathBuf},
    time::{Duration, SystemTime},
};

use anyhow::{Context, Result, anyhow};
use fs_err as fs;

use crate::{
    config::{ControllerConfig, OrphanCheck, PathMapping},
    constants,
    qbit_api::{QbitClient, Torrent},
};

const DEFAULT_SCRIPT_FILE: &str = "orphan_cleanup.sh";

#[derive(Debug, Default, PartialEq, Eq)]
pub struct OrphanCheckStats {
    pub torrents_inspected: usize,
    pub referenced_paths: usize,
    pub orphan_entries: usize,
    pub orphan_bytes: u64,
}

pub async fn run_orphan_check(
    config: &ControllerConfig,
    qbit: &QbitClient,
    torrents: &[Torrent],
) -> Result<OrphanCheckStats> {
    if config.orphan_check.root_dirs.is_empty() {
        return Err(anyhow!(
            "orphan_check.root_dirs must contain at least one local directory"
        ));
    }

    log::info!("=========== Orphan data check ===========");

    let referenced_paths = collect_referenced_paths(config, qbit, torrents).await?;
    let root_dirs = local_root_dirs(&config.orphan_check)?;
    let mut stats = OrphanCheckStats {
        torrents_inspected: torrents.len(),
        referenced_paths: referenced_paths.len(),
        ..OrphanCheckStats::default()
    };

    let mut orphans = Vec::new();
    for root_dir in root_dirs {
        log::info!("scan      {}", root_dir.display());
        for entry in collect_orphan_entries(&root_dir, &referenced_paths, &config.orphan_check)? {
            let size = path_size(&entry)?;
            stats.orphan_entries += 1;
            stats.orphan_bytes += size;
            log::info!("orphan    {}", entry.display());
            orphans.push((entry, size));
        }
    }

    let script_path = cleanup_script_path(&config.orphan_check);
    write_cleanup_script(&script_path, &orphans, stats.orphan_bytes)?;

    log::info!(
        "==================== Orphan check summary ====================\n  \
         Torrents inspected       : {}\n  \
         Referenced paths         : {}\n  \
         Orphan entries           : {}\n  \
         Approx orphan size       : {}\n  \
         Cleanup script           : {}",
        stats.torrents_inspected,
        stats.referenced_paths,
        stats.orphan_entries,
        human_bytes(stats.orphan_bytes),
        script_path.display()
    );

    Ok(stats)
}

fn cleanup_script_path(config: &OrphanCheck) -> PathBuf {
    config.script_path.as_deref().map_or_else(
        || PathBuf::from(constants::CONFIG_DIR).join(DEFAULT_SCRIPT_FILE),
        PathBuf::from,
    )
}

/// Writes a shell script that removes every orphan entry. The script is only
/// generated here; it is never executed by this tool.
fn write_cleanup_script(path: &Path, orphans: &[(PathBuf, u64)], total_bytes: u64) -> Result<()> {
    let script = render_cleanup_script(orphans, total_bytes, time::OffsetDateTime::now_utc());
    fs::write(path, script)
        .with_context(|| format!("Failed to write cleanup script {}", path.display()))?;

    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(path, std::fs::Permissions::from_mode(0o755))?;
    }

    Ok(())
}

fn render_cleanup_script(
    orphans: &[(PathBuf, u64)],
    total_bytes: u64,
    generated_at: time::OffsetDateTime,
) -> String {
    let mut script = String::new();
    script.push_str("#!/usr/bin/env bash\n");
    script.push_str("# Generated by qbit_controller --orphan-check\n");
    script.push_str(&format!("# Generated at (UTC): {generated_at}\n"));
    script.push_str(&format!(
        "# Orphan entries: {} ({})\n",
        orphans.len(),
        human_bytes(total_bytes)
    ));
    script.push_str("# Review this list before running. Deletions are permanent.\n");
    script.push_str("set -euo pipefail\n\n");

    for (path, size) in orphans {
        script.push_str(&format!("# {}\n", human_bytes(*size)));
        script.push_str(&format!(
            "rm -rf -- {}\n",
            shell_quote(&path.to_string_lossy())
        ));
    }

    script
}

fn shell_quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', r"'\''"))
}

async fn collect_referenced_paths(
    config: &ControllerConfig,
    qbit: &QbitClient,
    torrents: &[Torrent],
) -> Result<HashSet<PathBuf>> {
    let mut paths = HashSet::new();

    for torrent in torrents {
        if let Some(content_path) = torrent.content_path.as_deref() {
            insert_mapped_path(&mut paths, content_path, &config.orphan_check.path_mappings);
        }

        let Some(hash) = torrent.hash.as_deref() else {
            continue;
        };

        let files = qbit
            .get_torrent_files(hash)
            .await
            .with_context(|| format!("Failed to fetch files for torrent hash {hash}"))?;

        for file in files {
            if let Some(content_path) = torrent.content_path.as_deref() {
                let content_path = normalize_path(&map_qbit_path(
                    content_path,
                    &config.orphan_check.path_mappings,
                ));
                if file.name
                    == content_path
                        .file_name()
                        .and_then(|name| name.to_str())
                        .unwrap_or("")
                {
                    paths.insert(content_path);
                    continue;
                }

                insert_mapped_path(
                    &mut paths,
                    &content_path.join(&file.name).to_string_lossy(),
                    &config.orphan_check.path_mappings,
                );
            }

            if let Some(save_path) = torrent_save_path(torrent) {
                insert_mapped_path(
                    &mut paths,
                    &Path::new(save_path).join(&file.name).to_string_lossy(),
                    &config.orphan_check.path_mappings,
                );
            }
        }
    }

    Ok(paths)
}

fn torrent_save_path(torrent: &Torrent) -> Option<&str> {
    torrent.save_path.as_deref().or_else(|| {
        torrent
            .content_path
            .as_deref()
            .and_then(|content_path| Path::new(content_path).parent())
            .and_then(Path::to_str)
    })
}

fn insert_mapped_path(paths: &mut HashSet<PathBuf>, qbit_path: &str, mappings: &[PathMapping]) {
    paths.insert(normalize_path(&map_qbit_path(qbit_path, mappings)));
}

fn map_qbit_path(path: &str, mappings: &[PathMapping]) -> PathBuf {
    let path = normalize_path(Path::new(path));
    let mut best_mapping: Option<&PathMapping> = None;
    let mut best_len = 0;

    for mapping in mappings {
        let qbit_prefix = normalize_path(Path::new(&mapping.qbit));
        if path.starts_with(&qbit_prefix) {
            let len = qbit_prefix.as_os_str().len();
            if len > best_len {
                best_mapping = Some(mapping);
                best_len = len;
            }
        }
    }

    let Some(mapping) = best_mapping else {
        return path;
    };

    let qbit_prefix = normalize_path(Path::new(&mapping.qbit));
    let relative = path.strip_prefix(&qbit_prefix).unwrap_or(Path::new(""));
    normalize_path(&Path::new(&mapping.local).join(relative))
}

fn local_root_dirs(config: &OrphanCheck) -> Result<Vec<PathBuf>> {
    config
        .root_dirs
        .iter()
        .map(|dir| {
            let path = normalize_path(Path::new(dir));
            if !path.is_dir() {
                return Err(anyhow!(
                    "orphan_check root is not a directory: {}",
                    path.display()
                ));
            }
            Ok(path)
        })
        .collect()
}

fn collect_orphan_entries(
    root_dir: &Path,
    referenced_paths: &HashSet<PathBuf>,
    config: &OrphanCheck,
) -> Result<Vec<PathBuf>> {
    let mut entries = Vec::new();
    collect_orphan_entries_inner(root_dir, referenced_paths, config, &mut entries)?;
    entries.sort();
    Ok(entries)
}

fn collect_orphan_entries_inner(
    dir: &Path,
    referenced_paths: &HashSet<PathBuf>,
    config: &OrphanCheck,
    entries: &mut Vec<PathBuf>,
) -> Result<bool> {
    let mut has_reference = referenced_paths.iter().any(|path| path.starts_with(dir));

    for entry in fs::read_dir(dir).with_context(|| format!("Failed to read {}", dir.display()))? {
        let entry = entry?;
        let path = normalize_path(&entry.path());
        if is_excluded(&path, config) || is_too_new(&path, config)? {
            has_reference = true;
            continue;
        }

        let file_type = entry.file_type()?;
        let child_has_reference = referenced_paths
            .iter()
            .any(|referenced| referenced.starts_with(&path));

        if file_type.is_dir() && child_has_reference {
            if collect_orphan_entries_inner(&path, referenced_paths, config, entries)? {
                has_reference = true;
            }
        } else if child_has_reference {
            has_reference = true;
        } else {
            entries.push(path);
        }
    }

    Ok(has_reference)
}

fn is_excluded(path: &Path, config: &OrphanCheck) -> bool {
    let Some(name) = path.file_name().and_then(|name| name.to_str()) else {
        return false;
    };
    config.exclude_names.iter().any(|exclude| exclude == name)
}

fn is_too_new(path: &Path, config: &OrphanCheck) -> Result<bool> {
    if config.min_age_minutes == 0 {
        return Ok(false);
    }

    let modified = fs::metadata(path)?
        .modified()
        .unwrap_or(SystemTime::UNIX_EPOCH);
    let min_age = Duration::from_secs(config.min_age_minutes * 60);
    Ok(modified.elapsed().unwrap_or_default() < min_age)
}

fn normalize_path(path: &Path) -> PathBuf {
    let mut normalized = PathBuf::new();
    for component in path.components() {
        normalized.push(component.as_os_str());
    }
    normalized
}

fn path_size(path: &Path) -> Result<u64> {
    let metadata = fs::metadata(path)?;
    if metadata.is_file() {
        return Ok(metadata.len());
    }

    let mut total = 0;
    for entry in fs::read_dir(path)? {
        total += path_size(&entry?.path())?;
    }
    Ok(total)
}

fn human_bytes(bytes: u64) -> String {
    const UNITS: [&str; 5] = ["B", "KiB", "MiB", "GiB", "TiB"];
    let mut size = bytes as f64;
    let mut unit = UNITS[0];
    for next_unit in UNITS.iter().skip(1) {
        if size < 1024.0 {
            break;
        }
        size /= 1024.0;
        unit = next_unit;
    }

    if unit == "B" {
        format!("{bytes} {unit}")
    } else {
        format!("{size:.2} {unit}")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn maps_longest_qbit_prefix_to_local_prefix() {
        let mappings = vec![
            PathMapping {
                qbit: "/data".to_owned(),
                local: "/mnt/data".to_owned(),
            },
            PathMapping {
                qbit: "/data/torrents".to_owned(),
                local: "/downloads".to_owned(),
            },
        ];

        assert_eq!(
            map_qbit_path("/data/torrents/movies/file.mkv", &mappings),
            PathBuf::from("/downloads/movies/file.mkv")
        );
    }

    #[test]
    fn quotes_paths_for_shell() {
        assert_eq!(shell_quote("/data/plain"), "'/data/plain'");
        assert_eq!(shell_quote("/data/it's $HOME"), r"'/data/it'\''s $HOME'");
    }

    #[test]
    fn renders_cleanup_script() {
        let orphans = vec![(PathBuf::from("/data/old movie"), 1536)];
        let script = render_cleanup_script(
            &orphans,
            1536,
            time::macros::datetime!(2026-01-02 03:04:05 UTC),
        );

        assert!(script.starts_with("#!/usr/bin/env bash\n"));
        assert!(script.contains("# Orphan entries: 1 (1.50 KiB)\n"));
        assert!(script.contains("set -euo pipefail\n"));
        assert!(script.contains("rm -rf -- '/data/old movie'\n"));
    }

    #[test]
    fn formats_bytes() {
        assert_eq!(human_bytes(512), "512 B");
        assert_eq!(human_bytes(1536), "1.50 KiB");
    }
}
